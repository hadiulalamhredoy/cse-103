//Print the 1 to 5 Number Using For loop 
#include<stdio.h>
int main()
{
    int i;
    for(i =1;i<=5;i=i+2)
    {
        printf("%d\n",i);
    }
      
    
}
//Print the 100 to 1 Reverse Number Using For loop 
#include<stdio.h>
int main()
{
    int i;
    for(i=100;i<=1;i++)
    {
        printf("%d\n",i);
    }

    
}


